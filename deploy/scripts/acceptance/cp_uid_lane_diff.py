def bring_up(phase: str) -> None:
    section(f"bring up the lane ({phase})")
    compose(phase, "up", "-d")
    say()
    say("waiting for the control plane to answer on %s ..." % API_URL)
    import httpx

    deadline = time.time() + 90
    while time.time() < deadline:
        try:
            resp = httpx.get(f"{API_URL}/health", timeout=2)
            if resp.status_code < 500:
                say(f"/health -> HTTP {resp.status_code}")
                break
        except httpx.HTTPError:
            pass
        time.sleep(1)
    else:
        raise SystemExit("the control plane never answered; see `docker compose logs`")


def sweep_leftovers() -> None:
    """Kill/destroy anything a previous run (or a crashed probe) left behind.

    A leftover *running* sandbox holds its node reservation, and the smokes
    assert that reservations go back to zero after they kill their own -- so the
    reading would be about the leftover, not about the shape under test. This
    lane has its own compose project, so the sweep can only see its own.
    """
    section("0a. sweep this lane's leftovers (so the readings are about this run)")
    import httpx

    from e2b import Sandbox, Volume

    headers = {"X-API-Key": os.environ["E2B_API_KEY"]}
    paginator = Sandbox.list()
    ids: list[str] = []
    while paginator.has_next:
        ids.extend(s.sandbox_id for s in paginator.next_items())
    say(f"  leftover sandboxes: {ids}")
    for sandbox_id in ids:
        say(f"  kill {sandbox_id} -> {Sandbox.kill(sandbox_id)}")
    volumes = httpx.get(f"{API_URL}/volumes", headers=headers, timeout=30).json()
    for item in volumes if isinstance(volumes, list) else []:
        say(f"  destroy volume {item['volumeID']} -> {Volume.destroy(item['volumeID'])}")
    snapshots = httpx.get(f"{API_URL}/snapshots", headers=headers, timeout=30).json()
    for item in snapshots if isinstance(snapshots, list) else []:
        resp = httpx.delete(
            f"{API_URL}/snapshots/{item['snapshotID']}", headers=headers, timeout=60
        )
        say(f"  destroy snapshot {item['snapshotID']} -> HTTP {resp.status_code}")
    time.sleep(2)
    nodes = httpx.get(
        f"{API_URL}/internal/nodes", headers={"X-Internal-Key": INTERNAL_KEY}, timeout=30
    ).json()
    say(
        "  reservations after the sweep: "
        + str({n["nodeID"]: n["reservedMemoryMB"] for n in nodes})
    )


def tear_down(phase: str) -> None:
    section(f"tear the lane down ({phase}, `down -v`)")
    compose(phase, "down", "-v", "--remove-orphans")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--phase", choices=("lane", "shared"), default="lane")
    parser.add_argument("--up", action="store_true", help="bring the lane up first")
    parser.add_argument("--down", action="store_true", help="tear the lane down and exit")
    parser.add_argument("--only", help="run only this criterion (shape|create|logs|pause|"
                                      "snapshot|template|volume|delete|smokes)")
    args = parser.parse_args()

    # Same env contract as the two smoke scripts: the SDK reads these itself.
    os.environ.setdefault("E2B_API_KEY", "local-key")
    os.environ.setdefault("E2B_INTERNAL_API_KEY", INTERNAL_KEY)
    os.environ.setdefault("E2B_API_URL", API_URL)
    os.environ.setdefault("E2B_SANDBOX_URL", SANDBOX_URL)
    os.environ.setdefault("E2B_VOLUME_API_URL", API_URL)
    if args.down:
        tear_down(args.phase)
        return 0
    ensure_overrides(args.phase)
    if args.up:
        bring_up(args.phase)
    sweep_leftovers()

    run = lambda name: args.only in (None, name)  # noqa: E731

    def guard(name: str, fn, *fn_args) -> None:
        """Run one criterion; a raised exception is a reading, not an abort."""
        if not run(name):
            return
        try:
            fn(*fn_args)
        except Exception as exc:  # noqa: BLE001
            say(f"  criterion raised {type(exc).__name__}: {exc}")
            record(f"{name} (criterion raised)", False, f"{type(exc).__name__}: {exc}")

    guard("shape", crit_shape, args.phase)
    sandbox_id = None
    if run("create"):
        try:
            sandbox_id = crit_create_and_first_command()
        except Exception as exc:  # noqa: BLE001
            say(f"  criterion raised {type(exc).__name__}: {exc}")
            record("create (criterion raised)", False, f"{type(exc).__name__}: {exc}")
    if sandbox_id and run("logs"):
        guard("logs", crit_logs, sandbox_id)
    guard("pause", crit_pause_resume)
    guard("snapshot", crit_snapshot_restore)
    guard("template", crit_template_build, args.phase)
    guard("volume", crit_volume_rw)
    guard("delete", crit_delete)
    guard("smokes", crit_smokes, args.phase)

    section("summary")
    failed = 0
    for name, ok, detail in results:
        say(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"  ({detail})" if detail else ""))
        failed += 0 if ok else 1
    say(f"  {len(results) - failed}/{len(results)} criteria PASS")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
