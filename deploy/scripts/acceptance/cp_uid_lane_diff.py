def crit_create_and_first_command() -> str:
    """create + first command; returns the sandbox id."""
    section("1. create + 2. first command (through the gateway)")
    from e2b import Sandbox

    sandbox = Sandbox.create(timeout=300)
    say(f"  created {sandbox.sandbox_id}")
    route = sh(
        [
            "curl",
            "-sS",
            f"{API_URL}/internal/routes/{sandbox.sandbox_id}",
            "-H",
            f"X-Internal-Key: {INTERNAL_KEY}",
        ]
    ).stdout.strip()
    say(f"  route: {route}")
    result = sandbox.commands.run("echo cpuid-first-command-ok")
    say(f"  stdout={result.stdout!r} stderr={result.stderr!r} exit={result.exit_code}")
    record(
        "create lands a sandbox that answers its first command",
        result.stdout == "cpuid-first-command-ok\n" and result.exit_code == 0,
        route,
    )
    return sandbox.sandbox_id


def crit_logs(sandbox_id: str) -> None:
    section("3. GET /sandboxes/{id}/logs (+ kill the create criterion's sandbox)")
    import httpx

    resp = httpx.get(
        f"{API_URL}/sandboxes/{sandbox_id}/logs",
        headers={"X-API-Key": os.environ["E2B_API_KEY"]},
        timeout=30,
    )
    say(f"  HTTP {resp.status_code}")
    say(f"  {json.dumps(resp.json(), indent=2)}")
    lines = [entry.get("line") for entry in resp.json()] if resp.status_code == 200 else []
    record(
        "GET /logs returns the command log for the run above",
        resp.status_code == 200
        and {
            "> /bin/bash -l -c echo cpuid-first-command-ok",
            "cpuid-first-command-ok",
            "exit: 0",
        }.issubset(set(lines)),
        f"lines={lines}",
    )
    # The create criterion's sandbox is only here to be measured; kill it so the
    # node reservation goes back (the delete criterion asserts exactly that).
    from e2b import Sandbox

    killed = Sandbox.kill(sandbox_id)
    say(f"  kill({sandbox_id}) -> {killed}")


def crit_pause_resume() -> None:
    section("4. pause + resume")
    from e2b import Sandbox

    sandbox = Sandbox.create(
        api_key=os.environ["E2B_API_KEY"], sandbox_url=SANDBOX_URL, timeout=300
    )
    try:
        say(f"  created {sandbox.sandbox_id}")
        say(f"  pause() -> {sandbox.pause()}")
        state = Sandbox.get_info(sandbox.sandbox_id).state
        say(f"  get_info().state after pause -> {state}")
        again = Sandbox.connect(sandbox.sandbox_id)
        resumed_state = Sandbox.get_info(sandbox.sandbox_id).state
        result = again.commands.run("echo cpuid-after-resume")
        say(f"  state after connect -> {resumed_state}")
        say(f"  stdout={result.stdout!r} exit={result.exit_code}")
        record(
            "pause freezes and resume restores the sandbox",
            state == "paused"
            and resumed_state == "running"
            and result.stdout == "cpuid-after-resume\n",
            f"paused={state} resumed={resumed_state}",
        )
    finally:
        sandbox.kill()


def crit_snapshot_restore() -> None:
    section("5. snapshot + restore")
    from e2b import Sandbox

    sandbox = Sandbox.create(timeout=300)
    clone = None
    try:
        sandbox.files.write("workspace/cpuid-snap.txt", "cpuid-snapshot-data")
        snapshot = sandbox.create_snapshot(name="cpuid-lane")
        say(f"  snapshot_id={snapshot.snapshot_id} names={snapshot.names}")
        clone = Sandbox.create(snapshot.snapshot_id, timeout=300)
        restored = clone.files.read("workspace/cpuid-snap.txt")
        say(f"  restored file -> {restored!r}")
        record(
            "a snapshot restores into a new sandbox with its files",
            snapshot.snapshot_id.startswith("snap_")
            and restored == "cpuid-snapshot-data",
            snapshot.snapshot_id,
        )
        say(f"  delete_snapshot -> {sandbox.delete_snapshot(snapshot.snapshot_id)}")
    finally:
        if clone is not None:
            clone.kill()
        sandbox.kill()


def crit_template_build(phase: str) -> None:
    section(
        "6. template build (buildkit -> _oci tar -> worker unpack) [%s]" % phase
    )
    from e2b import Sandbox, Template

    name = "cpuid-lane-template"
    log: list[str] = []
    template = Template().from_dockerfile(
        "FROM python:3.11-slim\nRUN echo cpuid-template-marker > /cpuid-marker"
    )
    try:
        info = Template.build(
            template,
            name,
            api_url=API_URL,
            api_key=os.environ["E2B_API_KEY"],
            on_build_logs=lambda entry: log.append(f"{entry.level}: {entry.message}"),
        )
    except Exception as exc:  # noqa: BLE001 - the failure *is* the reading
        for line in log:
            say(f"  build log: {line}")
        say(f"  Template.build raised {type(exc).__name__}: {exc}")
        record(
            "template build (this phase)",
            False,
            f"{type(exc).__name__}: {exc}",
        )
        return
    say(f"  template_id={info.template_id} image={getattr(info, 'image', None)}")
    slug = f"e2b-local_{info.template_id}"
    # Where the artifacts went, read off the containers themselves.
    docker_exec(
        "control-plane",
        "sh",
        "-c",
        "ls -la /var/lib/e2b-sandboxes/_images/_oci/ && "
        'stat -c "%n %F %a %u:%g" /var/lib/e2b-sandboxes/_images/_oci/*',
    )
    sandbox = Sandbox.create(template=name, timeout=300)
    try:
        result = sandbox.commands.run("cat /cpuid-marker")
        say(f"  stdout={result.stdout!r} exit={result.exit_code}")
        route = sh(
            [
                "curl",
                "-sS",
                f"{API_URL}/internal/routes/{sandbox.sandbox_id}",
                "-H",
                f"X-Internal-Key: {INTERNAL_KEY}",
            ]
        ).stdout.strip()
        say(f"  route: {route}")
        # The worker's unpack lands in its *own* cache (node-local volume), and
        # the sidecar link it writes next to it belongs to the worker's uid --
        # the tar itself stays 65533's. That is the "tar shared, rootfs local"
        # half of the shape, and the uid half of it.
        for service in ("worker-1", "worker-2", "worker-3"):
            docker_exec(
                service,
                "sh",
                "-c",
                "ls -la /var/lib/e2b-sandboxes/_images/ | "
                f"grep -E '({slug})' || echo '(no unpacked {slug} here)'",
            )
        linking = docker_exec(
            service_of(route) or "worker-1",
            "sh",
            "-c",
            f'stat -c "%n %F %a %u:%g" /var/lib/e2b-sandboxes/_images/_oci/{slug}.link',
        )
        record(
            "template build -> _oci tar -> worker unpack -> image rootfs",
            result.stdout == "cpuid-template-marker\n"
            and result.exit_code == 0
            and linking.returncode == 0
            and "65534:65534" in (linking.stdout or ""),
            route,
        )
    finally:
        sandbox.kill()


def crit_volume_rw() -> None:
    section("7. volume mount read-write")
    from e2b import Sandbox, Volume

    volume = Volume.create("cpuid-lane-vol")
    sandbox = None
    try:
        volume.write_file("host.txt", b"written-from-the-host")
        sandbox = Sandbox.create(volume_mounts={"mnt/data": volume.volume_id}, timeout=300)
        try:
            read = sandbox.commands.run("cat mnt/data/host.txt")
        except Exception as exc:  # noqa: BLE001 - the failure *is* the reading
            say(f"  sandbox read raised {type(exc).__name__}: {exc}")
            # Why it failed, from three places: the sandbox's own view (does the
            # link target exist *there*?), the control plane (where the bytes
            # are), and a worker (does that path exist on this side at all?).
            sandbox.files.write(
                "workspace/volume_probe.py",
                "import os\n"
                "for p in ['/home/user/mnt/data',\n"
                "          '/var/lib/e2b-sandboxes',\n"
                "          '/var/lib/e2b-sandboxes/_volumes']:\n"
                "    try:\n"
                "        print(p, 'ok', oct(os.stat(p).st_mode))\n"
                "    except OSError as e:\n"
                "        print(p, 'ERR', e)\n",
            )
            for command in (
                "readlink mnt/data",
                "python3 workspace/volume_probe.py",
            ):
                say(f"  [sandbox] $ {command}")
                try:
                    out = sandbox.commands.run(command).stdout
                except Exception as inner:  # noqa: BLE001 - the exit code is a reading
                    out = str(inner)
                for line in out.rstrip("\n").splitlines():
                    say(f"  [sandbox] {line}")
            docker_exec(
                "control-plane",
                "sh",
                "-c",
                "ls -ld /var/lib/e2b-sandboxes/_volumes /var/lib/e2b-sandboxes/_volumes/*/",
            )
            docker_exec(
                "worker-1",
                "sh",
                "-c",
                "ls -ld /var/lib/e2b-sandboxes/_volumes 2>&1 || true",
            )
            record("a mounted volume reads and writes in both directions", False, str(exc))
            return
        say(f"  sandbox read -> {read.stdout!r}")
        wrote = sandbox.commands.run(
            "echo written-from-the-sandbox > mnt/data/sandbox.txt && echo ok"
        )
        say(f"  sandbox write -> {wrote.stdout!r} exit={wrote.exit_code}")
        back = volume.read_file("sandbox.txt").decode()
        say(f"  host read back -> {back!r}")
        record(
            "a mounted volume reads and writes in both directions",
            read.stdout == "written-from-the-host"
            and wrote.stdout == "ok\n"
            and back == "written-from-the-sandbox\n",
            f"{read.stdout!r} / {wrote.stdout!r} / {back!r}",
        )
    finally:
        if sandbox is not None:
            sandbox.kill()
        Volume.destroy(volume.volume_id)


def crit_delete() -> None:
    section("8. delete")
    import httpx

    from e2b import Sandbox

    sandbox = Sandbox.create(timeout=300)
    sandbox_id = sandbox.sandbox_id
    say(f"  created {sandbox_id}")
    killed = sandbox.kill()
    say(f"  kill() -> {killed}")
    gone = httpx.get(
        f"{API_URL}/sandboxes/{sandbox_id}",
        headers={"X-API-Key": os.environ["E2B_API_KEY"]},
        timeout=30,
    )
    say(f"  GET /sandboxes/{sandbox_id} -> HTTP {gone.status_code}")
    # The release is asynchronous (the node answers the next heartbeat with the
    # new ledger), so poll briefly instead of reading one instant.
    reserved: dict[str, int] = {}
    for _ in range(30):
        nodes = httpx.get(
            f"{API_URL}/internal/nodes",
            headers={"X-Internal-Key": INTERNAL_KEY},
            timeout=30,
        ).json()
        reserved = {
            n["nodeID"]: n["reservedMemoryMB"] for n in nodes if n["address"] != "local://"
        }
        if all(v == 0 for v in reserved.values()):
            break
        time.sleep(1)
    say(f"  after-delete reservations: {reserved}")
    record(
        "delete removes the record and releases the node's reservation",
        killed is True and gone.status_code == 404 and all(v == 0 for v in reserved.values()),
        f"kill={killed} http={gone.status_code} reserved={reserved}",
    )


