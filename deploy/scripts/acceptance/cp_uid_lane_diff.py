def crit_shape(phase: str) -> None:
    section("0. the uid shape: control plane 65533 (CapEff 0), workers 65534")
    compose(phase, "ps")
    for service in ("control-plane", "worker-1", "worker-2", "worker-3", "c3-agent"):
        user = sh(
            ["docker", "inspect", CONTAINER[service], "--format", "{{.Config.User}}"]
        ).stdout.strip()
        ident = docker_exec(service, "id").stdout.strip()  # type: ignore[union-attr]
        say(f"  -> {service}: Config.User={user}")
        record(f"{service} runs as the manifest's uid", ident.startswith("uid="), ident)
    caps = docker_exec(
        "control-plane",
        "sh",
        "-c",
        'grep -E "^(CapEff|CapBnd)" /proc/self/status',
    ).stdout.strip()  # type: ignore[union-attr]
    record(
        "control plane CapEff is 0",
        "CapEff:\t0000000000000000" in caps,
        caps.replace("\n", " "),
    )
    # The hand-over is split by identity: the control plane's volume is 65533,
    # the workers' is 65534 (Task 3's `uid_of` in the root one-shot).
    init = sh(["docker", "logs", CONTAINER["image-cache-init"]])
    init_log = (init.stdout or "") + (init.stderr or "")
    handed = dict(
        re.findall(
            r"^image-cache-init: (/cache/\S+) is owned by uid (\d+)$",
            init_log,
            flags=re.MULTILINE,
        )
    )
    control = {path: uid for path, uid in handed.items() if path.startswith("/cache/control")}
    worker = {path: uid for path, uid in handed.items() if path.startswith("/cache/worker")}
    record(
        "hand-over gave every control-data target 65533",
        set(control) == {
            "/cache/control/_builds",
            "/cache/control/_images",
            "/cache/control/_migrate",
            "/cache/control/_secrets",
            "/cache/control/_snapshots",
            "/cache/control/_templates",
        }
        and set(control.values()) == {"65533"},
        f"{len(control)} targets: {sorted(control)}",
    )
    record(
        "hand-over gave every worker-data target 65534",
        len(worker) == 3 and set(worker.values()) == {"65534"},
        f"{len(worker)} targets: {sorted(worker)}",
    )
    # The D24 volume store and the two writable roots are the other two shapes
    # the one-shot reports -- the store's line carries its own wording (it is a
    # non-recursive hand-over), so it is read by name.
    record(
        "the volume store went to the control plane's uid",
        "image-cache-init: /cache/control/_volumes is owned by uid 65533" in init_log,
        "non-recursive hand-over of _volumes",
    )
    record(
        "both writable roots are their volume's uid",
        "image-cache-init: /cache/control is writable by uid 65533 (owner=65533 mode=755)"
        in init_log
        and "image-cache-init: /cache/worker is writable by uid 65534 (owner=65534 mode=755)"
        in init_log,
        "control 65533 / worker 65534",
    )
    # The control plane still owns what it writes: a file it creates under the
    # volume root must come out 65533 (the whole point of the split hand-over).
    docker_exec(
        "control-plane",
        "sh",
        "-c",
        "touch /var/lib/e2b-sandboxes/.cpuid-owner-probe && "
        'stat -c "%n %a %u:%g" /var/lib/e2b-sandboxes/.cpuid-owner-probe && '
        "rm -f /var/lib/e2b-sandboxes/.cpuid-owner-probe",
    )


