results: list[tuple[str, bool, str]] = []


def say(text: str = "") -> None:
    print(text, flush=True)


def section(title: str) -> None:
    say()
    say(f"===== {title} =====")


def sh(argv: list[str], *, env: dict[str, str] | None = None, cwd: Path | None = None):
    """Run one command, echo it and its raw output, return the CompletedProcess."""
    say(f"$ {' '.join(argv)}")
    proc = subprocess.run(
        argv,
        capture_output=True,
        text=True,
        env={**os.environ, **(env or {})},
        cwd=str(cwd or REPO),
    )
    out = (proc.stdout or "") + (proc.stderr or "")
    for line in out.rstrip("\n").splitlines():
        say(f"  {line}")
    say(f"  [exit {proc.returncode}]")
    return proc


def compose_files(phase: str) -> list[str]:
    files = ["-f", str(BASE_COMPOSE), "-f", str(LANE_OVERRIDE)]
    if phase == "shared":
        files += ["-f", str(SHARED_OVERRIDE)]
    return files


def ensure_overrides(phase: str) -> None:
    """Write the gitignored ``tmp/`` overrides when they are missing.

    The readings are produced by *these* files, so they are printed in the
    report; on a fresh checkout this recreates them. Existing files are left
    alone (a human may be iterating on them) and every file is validated by
    ``docker compose config`` the moment it is written.
    """
    wanted = {LANE_OVERRIDE: _LANE_OVERRIDE}
    if phase == "shared":
        wanted[SHARED_OVERRIDE] = _SHARED_OVERRIDE
    wrote = False
    for path, text in wanted.items():
        if path.exists():
            say(f"  using the existing override {path}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        say(f"  wrote {path} ({len(text)} bytes)")
        wrote = True
    if wrote:
        proc = sh(["docker", "compose", "-p", PROJECT, *compose_files(phase), "config"])
        if proc.returncode != 0:
            raise SystemExit("the generated override does not render; see above")


def compose(phase: str, *args: str, env: dict[str, str] | None = None):
    return sh(["docker", "compose", "-p", PROJECT, *compose_files(phase), *args], env=env)


def docker_exec(service: str, *args: str):
    return sh(["docker", "exec", CONTAINER[service], *args])


def record(name: str, ok: bool, detail: str = "") -> None:
    results.append((name, ok, detail))


def service_of(route: str) -> str | None:
    """``worker-1`` from a ``/internal/routes`` body, when it names one of ours."""
    try:
        node_id = json.loads(route).get("nodeID")
    except ValueError:
        return None
    return node_id if node_id in CONTAINER else None


