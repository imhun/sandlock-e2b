#!/usr/bin/env python3
"""Task 5 Steps 1-2: the local-lane differential for the control-plane uid move.

The plan (`docs/superpowers/plans/2026-10-09-control-plane-uid-relocation.md`,
Task 5) is: bring the **local multi-node compose lane** up, run the eight
criteria the move has to keep working (create / first command / ``GET /logs`` /
pause+resume / snapshot+restore / template build / volume mount read-write /
delete) plus the two shipped smokes, and keep the raw readings. One command,
re-runnable, so the gated production step and a human can re-measure the same
thing.

Two phases, because the lane as shipped cannot exercise the template path at
all (read the two arms of `--phase` below):

* ``--phase lane`` (default) -- the lane exactly as
  `deploy/compose/docker-compose.multinode.yml` declares it (plus the gitignored
  capacity override `tmp/task5-cpuid/override-lane.yml`, which exists for the
  disk-usage and process-budget reasons recorded there). In this shape the
  control plane carries ``E2B_IMAGE_REGISTRY: registry.example.com/e2b`` (a
  placeholder host) and there is **no buildkitd** anywhere in the stack, so
  ``Template.build`` fails before it writes anything -- the criterion is printed
  as its raw failure, not as a green.
* ``--phase shared`` -- the same lane plus
  `tmp/task5-cpuid/override-shared-namespaces.yml`: a rootless buildkit the
  control plane reaches over a shared socket, ``E2B_IMAGE_REGISTRY=""`` (the
  no-registry branch, which is the branch **the fleet runs**: `deploy/k8s/*.yaml`
  set no registry either), one shared ``oci-shared`` volume mounted at
  ``_images/_oci`` in the control plane, all three workers and the hand-over
  one-shot, and the control plane's ``control-data`` mounted at the workers'
  ``_volumes``. Those are the two namespaces this lane splits ("one directory,
  two identities"): the tar store (control plane 65533 writes, worker 65534
  reads and unpacks into its own node-local cache) and the volume store (the
  control plane creates ``<store>/<volume_id>`` as 1777, the sandbox's pooled
  uid writes into it).

What this lane can prove about the change itself (and does, in section 0):
the control plane runs as 65533 with ``CapEff`` 0 and still creates/reads/writes
everything it owns; the workers and the agent's face A stay 65534; the root
one-shot's hand-over is split by volume (65533 on the control plane's volume,
65534 on the workers'). What it **cannot** prove, and must not be read as
green: the shared ``_snapshots``/``_migrate`` cross-uid relations (this lane has
two separate volumes, `control-data` and `worker-data`) and anything about the
k8s mounts / QoS / namespace shape. Those are k8s-shape facts and belong to the
gated production step (`AGENTS.md`: 线上只做本地证明不了的那些形状事实).

Usage::

    python3 deploy/scripts/acceptance/cp_uid_lane_diff.py --up            # lane phase
    python3 deploy/scripts/acceptance/cp_uid_lane_diff.py --phase shared --up
    python3 deploy/scripts/acceptance/cp_uid_lane_diff.py --down          # tear it down

Env knobs: ``E2B_API_KEY`` (default ``local-key``, the lane's own value),
``CPUID_PYTHON`` (interpreter for the two smoke scripts; defaults to
``tmp/venv/bin/python`` when it exists, else this interpreter).
"""

